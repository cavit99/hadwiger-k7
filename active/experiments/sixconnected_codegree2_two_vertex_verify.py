#!/usr/bin/env python3
"""Verify the adjacent two-vertex quotient in the codegree-two campaign.

Let J have eight vertices, minimum degree at least three, and no K_6^-
minor.  Add a centre v complete to J and an adjacent pair x,y, with no
edges from v to x,y.  This verifier exhausts every attachment of x,y to J
for which the resulting graph is six-connected.  Every such graph has a
K_7^- minor.

Every eight-vertex graph is generated by extending an order-seven graph
from NetworkX's atlas.  The minor oracle is imported from the separately
retained degree-eight verifier and is exact.  Run from the repository root:

    UV_CACHE_DIR=/tmp/hadwiger-uv-cache uv run python -B \
      active/experiments/sixconnected_codegree2_two_vertex_verify.py
"""

from __future__ import annotations

from collections import Counter
from hashlib import sha256
import importlib.util
from itertools import combinations
from pathlib import Path

import networkx as nx


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "results" / "hc7_k7minus_sixconnected_degree_eight_low_codegree_verify.py"
EXPECTED_SOURCE_SHA256 = (
    "d721c181a8388feb7901e8ab04f704c19679cfb56551752756a45733f28d6fdc"
)
if sha256(SOURCE.read_bytes()).hexdigest() != EXPECTED_SOURCE_SHA256:
    raise RuntimeError("the imported exact minor engine revision changed")
SPEC = importlib.util.spec_from_file_location("degree_eight_verify", SOURCE)
assert SPEC and SPEC.loader
TOOLS = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(TOOLS)


def quotient(
    graph: nx.Graph,
    first_missed: tuple[int, ...],
    second_missed: tuple[int, ...],
) -> nx.Graph:
    """Add centre 8 and adjacent exterior vertices 9,10."""

    answer = graph.copy()
    answer.add_nodes_from((8, 9, 10))
    answer.add_edges_from((8, vertex) for vertex in range(8))
    answer.add_edges_from(
        (9, vertex) for vertex in range(8) if vertex not in first_missed
    )
    answer.add_edges_from(
        (10, vertex) for vertex in range(8) if vertex not in second_missed
    )
    answer.add_edge(9, 10)
    return answer


def connected_after_deletion(adjacency: tuple[int, ...], deleted: int) -> bool:
    remaining = ((1 << len(adjacency)) - 1) & ~deleted
    if not remaining:
        return True
    reached = remaining & -remaining
    while True:
        expanded = reached
        scan = reached
        while scan:
            bit = scan & -scan
            scan ^= bit
            expanded |= adjacency[bit.bit_length() - 1] & remaining
        if expanded == reached:
            return reached == remaining
        reached = expanded


H_CUTS = tuple(
    sum(1 << vertex for vertex in cut)
    for order in range(5)
    for cut in combinations(range(10), order)
)


def is_six_connected(graph: nx.Graph) -> bool:
    """Check six-connectivity using the special quotient structure.

    If the centre survives a cut of order at most five, all surviving
    boundary vertices lie in one component through it.  The only possible
    further component is the adjacent exterior pair, and a five-cut can
    isolate that pair exactly when both exterior vertices have the same
    five boundary neighbours.  If the centre is deleted, at most four
    further vertices are deleted, so it remains only to test those cuts in
    the ten-vertex centre-deleted graph.
    """

    if min(dict(graph.degree()).values()) < 6:
        return False
    first_boundary = frozenset(graph[9]).intersection(range(8))
    second_boundary = frozenset(graph[10]).intersection(range(8))
    if first_boundary == second_boundary and len(first_boundary) == 5:
        return False

    reduced = nx.convert_node_labels_to_integers(
        graph.subgraph(set(range(8)) | {9, 10})
    )
    adjacency = TOOLS.adjacency_tuple(reduced)
    return all(connected_after_deletion(adjacency, deleted) for deleted in H_CUTS)


def valid_model(adjacency: tuple[int, ...], bags: tuple[int, ...]) -> bool:
    if len(bags) != 7:
        return False
    if not all(TOOLS.connected(adjacency, bag) for bag in bags):
        return False
    return sum(
        not TOOLS.touching(adjacency, left, right)
        for left, right in combinations(bags, 2)
    ) <= 1


def main() -> None:
    TOOLS.calibrate_minor_engine()

    bases = [graph for graph in nx.graph_atlas_g() if len(graph) == 7]
    raw = [
        graph
        for base in bases
        for graph in TOOLS.extensions_of_atlas_graph(base)
        if min(dict(graph.degree()).values()) >= 3
    ]
    representatives = TOOLS.isomorphism_representatives(raw)
    local_survivors = [
        graph
        for graph in representatives
        if TOOLS.near_clique_minor_model(TOOLS.adjacency_tuple(graph), 6) is None
    ]

    profile_distribution: Counter[int] = Counter()
    degree_feasible = 0
    six_connected = 0
    exact_searches = 0
    cached_models: list[tuple[int, ...]] = []
    certificate_hash = sha256()

    for graph in local_survivors:
        degrees = tuple(graph.degree(vertex) for vertex in range(8))
        missable = tuple(vertex for vertex in range(8) if degrees[vertex] >= 4)
        profiles = tuple(
            missed
            for order in range(4)
            for missed in combinations(missable, order)
        )
        profile_distribution[len(profiles)] += 1

        for first_index, first in enumerate(profiles):
            first_set = frozenset(first)
            for second in profiles[first_index:]:
                # A local degree-four vertex may be missed by at most one
                # of x,y.  Cubic vertices were excluded from every missed
                # set when the profiles were constructed.
                if any(
                    degrees[vertex] == 4
                    for vertex in first_set.intersection(second)
                ):
                    continue
                degree_feasible += 1
                host = quotient(graph, first, second)
                if not is_six_connected(host):
                    continue
                six_connected += 1

                adjacency = TOOLS.adjacency_tuple(host)
                model = next(
                    (
                        candidate
                        for candidate in cached_models
                        if valid_model(adjacency, candidate)
                    ),
                    None,
                )
                if model is None:
                    exact_searches += 1
                    model = TOOLS.near_clique_minor_model(adjacency, 7)
                    if model is None:
                        raise RuntimeError(
                            "six-connected target-free quotient: "
                            f"{TOOLS.graph_code(graph)} {first} {second}"
                        )
                    cached_models.append(model)
                TOOLS.verify_model(adjacency, model, 7)
                line = (
                    f"{TOOLS.graph_code(graph)} {','.join(map(str, first)) or '-'} "
                    f"{','.join(map(str, second)) or '-'} {TOOLS.model_text(model)}\n"
                )
                certificate_hash.update(line.encode())

    expected_distribution = {
        1: 6,
        2: 9,
        4: 58,
        8: 127,
        15: 291,
        26: 421,
        42: 403,
        64: 192,
        93: 55,
    }
    if len(representatives) != 2_590 or len(local_survivors) != 1_562:
        raise RuntimeError("the eight-vertex local census changed")
    if dict(sorted(profile_distribution.items())) != expected_distribution:
        raise RuntimeError("the attachment-profile distribution changed")
    if degree_feasible != 668_408 or six_connected != 611_678:
        raise RuntimeError(
            f"quotient counts changed: {degree_feasible}, {six_connected}"
        )

    digest = certificate_hash.hexdigest()
    expected_digest = (
        "c54b07a9dfa35f6d5d4c41b89f982379d074f0aea0231503d30c17fd9e002858"
    )
    if digest != expected_digest:
        raise RuntimeError(f"certificate digest changed: {digest}")

    print("GREEN six-connected codegree-two adjacent-pair quotient")
    print(f"local_isomorphism_classes={len(representatives)}")
    print(f"K6minus_free_local_classes={len(local_survivors)}")
    print(f"profile_distribution={dict(sorted(profile_distribution.items()))}")
    print(f"degree_feasible_attachment_pairs={degree_feasible}")
    print(f"six_connected_quotients={six_connected}")
    print(f"exact_minor_searches={exact_searches}")
    print(f"cached_model_templates={len(cached_models)}")
    print(f"certificate_digest={digest}")


if __name__ == "__main__":
    main()
